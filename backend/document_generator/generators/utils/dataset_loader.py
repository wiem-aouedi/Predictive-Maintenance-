"""
Utility functions for loading simulator datasets.
"""

from pathlib import Path

import pandas as pd


class DatasetLoader:
    """
    Loads datasets generated by the simulator.
    """

    def __init__(self, raw_data_dir: Path):
        self.raw_data_dir = raw_data_dir

    def load_sensor_data(self) -> pd.DataFrame:
        """
        Load the raw sensor dataset.

        Returns
        -------
        pd.DataFrame
            Sensor measurements sorted by machine and timestamp.
        """

        file_path = self.raw_data_dir / "sensor_data_raw.csv"

        if not file_path.exists():
            raise FileNotFoundError(
                f"Sensor dataset not found: {file_path}"
            )

        df = pd.read_csv(file_path)

        df["timestamp"] = pd.to_datetime(df["timestamp"])

        df = df.sort_values(
            by=["machine_id", "timestamp"]
        ).reset_index(drop=True)

        return df

    def load_machine_data(self) -> pd.DataFrame:
        """
        Load machine metadata.
        """

        file_path = self.raw_data_dir / "machines.csv"

        if not file_path.exists():
            raise FileNotFoundError(
                f"Machine dataset not found: {file_path}"
            )

        return pd.read_csv(file_path)